/** Offline conservative panel envelopes from the exact owner-supplied CAD. */
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {Matrix4,Vector3} from 'three';
const input=await readFile('assets/source/robots/4481-era-ii/upload/Rembrandts 4481 Worlds.glb');
if(createHash('sha256').update(input).digest('hex')!=='6502ca903919ef90fab559e73bab930cd6335a362fc9585fb2a552beca893fc4')throw Error('Rembrandts source hash changed');
const doc=await new NodeIO().registerExtensions(ALL_EXTENSIONS).readBinary(input);
const cross=(o,a,b)=>(a[0]-o[0])*(b[1]-o[1])-(a[1]-o[1])*(b[0]-o[0]);
function hull(points){
 const sorted=[...new Map(points.map(p=>[p.join(','),p])).values()].sort((a,b)=>a[0]-b[0]||a[1]-b[1]),lo=[],hi=[];
 for(const p of sorted){while(lo.length>1&&cross(lo.at(-2),lo.at(-1),p)<=0)lo.pop();lo.push(p);}
 for(const p of sorted.slice().reverse()){while(hi.length>1&&cross(hi.at(-2),hi.at(-1),p)<=0)hi.pop();hi.push(p);}
 return lo.slice(0,-1).concat(hi.slice(0,-1));
}
const boxes=[],counts={};
// Eight narrow intervals retain the changing panel height. Pad by 0.75 mm
// around the source, including prepared-mesh simplification/quantization.
const pad=.00075,round=x=>Number(x.toFixed(6));
for(const node of doc.getRoot().listNodes()){
 const name=node.getName();if(!['TR26-IN-4019','TR26-IN-4020'].includes(name)||!node.getMesh())continue;
 counts[name]=(counts[name]??0)+1;
 const matrix=new Matrix4().fromArray(node.getWorldMatrix()),points=[];
 for(const p of node.getMesh().listPrimitives()){
  const a=p.getAttribute('POSITION');for(let i=0;i<a.getCount();i++){
   const v=new Vector3(...a.getElement(i,[])).applyMatrix4(matrix);points.push([v.z,v.y-.223,-v.x]);
  }
 }
 const polygon=hull(points.map(p=>p.slice(0,2))),minX=Math.min(...polygon.map(p=>p[0])),maxX=Math.max(...polygon.map(p=>p[0]));
 const minZ=Math.min(...points.map(p=>p[2]))-pad,maxZ=Math.max(...points.map(p=>p[2]))+pad;
 for(let i=0;i<8;i++){
  const x0=minX+(maxX-minX)*i/8,x1=minX+(maxX-minX)*(i+1)/8;
  const ys=polygon.filter(p=>p[0]>=x0&&p[0]<=x1).map(p=>p[1]);
  for(let j=0;j<polygon.length;j++){
   const a=polygon[j],b=polygon[(j+1)%polygon.length];
   for(const x of [x0,x1])if(a[0]!==b[0]&&x>=Math.min(a[0],b[0])&&x<=Math.max(a[0],b[0]))ys.push(a[1]+(b[1]-a[1])*(x-a[0])/(b[0]-a[0]));
  }
  const lo=[x0-pad,Math.min(...ys)-pad,minZ],hi=[x1+pad,Math.max(...ys)+pad,maxZ];
  boxes.push({part:'intake',center:lo.map((v,k)=>round((v+hi[k])/2)),halfExtents:lo.map((v,k)=>round((hi[k]-v)/2))});
 }
}
if(counts['TR26-IN-4019']!==2||counts['TR26-IN-4020']!==1||boxes.length!==24)throw Error(`Unexpected panel inventory: ${JSON.stringify(counts)}`);
const text="// Generated by measure-intake-contacts.mjs from the hash-verified Worlds CAD.\n// Conservative 0.75 mm padding; original panel heights and slide remain intact.\nimport type { RobotCollider } from '../../types';\nexport const ERA_INTAKE_PANELS: RobotCollider[] = [\n"+boxes.map(b=>"  "+JSON.stringify(b)+",").join('\n')+'\n];\n';
await writeFile('src/robot/robots/4481-era-ii/intakeContacts.ts',text);
console.log(`Measured ${boxes.length} panel envelopes from three original solids.`);
